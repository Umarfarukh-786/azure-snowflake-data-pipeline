-- Run in a Snowflake worksheet using a role permitted to create these objects.
-- A running warehouse may incur charges. Suspend it when finished.
CREATE DATABASE IF NOT EXISTS DATA_ENGINEERING_DB;
CREATE SCHEMA IF NOT EXISTS DATA_ENGINEERING_DB.PUBLIC;

CREATE WAREHOUSE IF NOT EXISTS DATA_ENGINEERING_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

USE DATABASE DATA_ENGINEERING_DB;
USE SCHEMA PUBLIC;
USE WAREHOUSE DATA_ENGINEERING_WH;

CREATE TABLE IF NOT EXISTS SALES_RAW (
    ORDER_ID VARCHAR(30),
    ORDER_DATE DATE,
    CUSTOMER_ID VARCHAR(30),
    CUSTOMER_NAME VARCHAR(100),
    PRODUCT VARCHAR(100),
    QUANTITY NUMBER(10,0),
    UNIT_PRICE NUMBER(12,2),
    TOTAL_AMOUNT NUMBER(14,2),
    REGION VARCHAR(50)
);
