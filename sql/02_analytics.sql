USE DATABASE DATA_ENGINEERING_DB;
USE SCHEMA PUBLIC;
USE WAREHOUSE DATA_ENGINEERING_WH;

-- Basic load validation
SELECT COUNT(*) AS row_count FROM SALES_RAW;

SELECT
    COUNT_IF(ORDER_ID IS NULL) AS null_order_ids,
    COUNT_IF(CUSTOMER_ID IS NULL) AS null_customer_ids,
    COUNT_IF(QUANTITY <= 0) AS invalid_quantities,
    COUNT_IF(UNIT_PRICE < 0) AS invalid_prices
FROM SALES_RAW;

-- Duplicate-key check
SELECT ORDER_ID, COUNT(*) AS occurrences
FROM SALES_RAW
GROUP BY ORDER_ID
HAVING COUNT(*) > 1;

-- Example analytics-ready monthly sales summary
SELECT
    DATE_TRUNC('MONTH', ORDER_DATE) AS SALES_MONTH,
    REGION,
    COUNT(*) AS ORDER_COUNT,
    SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM SALES_RAW
GROUP BY 1, 2
ORDER BY 1, 2;

-- Example product summary
SELECT
    PRODUCT,
    SUM(QUANTITY) AS UNITS_SOLD,
    SUM(TOTAL_AMOUNT) AS REVENUE
FROM SALES_RAW
GROUP BY PRODUCT
ORDER BY REVENUE DESC;
